// Command kotlin-modelgen generates the wavelength-kmp wire models from the
// wavelength Go SDK's DTO definitions (sdk/wavewalletdk/types.go).
//
// The gomobile facade passes those DTOs across the binding as encoding/json
// output. They carry no json tags, so the wire keys are the Go field names
// verbatim (PascalCase, with Go acronyms such as SendIntentID, VTXOs, CSV).
// Generating the Kotlin side from the Go source keeps every @SerialName exact
// and lets CI detect drift whenever the pinned daemon changes.
//
// It parses the file syntactically (go/parser), so it needs no module
// resolution of wavelength's dependencies.
//
// Output:
//
//	<out>/model/Models.kt   public results, nested types and enums
//	<out>/wire/Requests.kt  internal *Request DTOs sent to the facade
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const (
	modelPkg = "engineering.lightning.wavelength.model"
	wirePkg  = "engineering.lightning.wavelength.wire"
)

// skipTypes are Go-only types (gRPC dial options, HTTP clients) that never
// cross the gomobile boundary.
var skipTypes = map[string]bool{
	"ConnectConfig": true,
	"Transport":     true,
}

type enumKind int

const (
	stringEnum enumKind = iota
	intEnum
)

type enumValue struct {
	goName string
	value  string // string literal value, or decimal for int enums
	doc    string
}

type enumDef struct {
	name   string
	kind   enumKind
	doc    string
	values []enumValue
}

type fieldDef struct {
	goName   string
	wireName string
	typ      ast.Expr
	doc      string
}

type structDef struct {
	name   string
	doc    string
	fields []fieldDef
}

type generator struct {
	enums   map[string]*enumDef
	structs map[string]*structDef
	order   []string
}

func main() {
	src := flag.String("src", "", "path to sdk/wavewalletdk/types.go")
	out := flag.String("out", "", "output root (the commonMain kotlin dir containing engineering/lightning/wavelength)")
	pin := flag.String("pin", "", "wavelength tag the source came from")
	goTypes := flag.String("go-types", "", "optional: also write a dependency-free copy of the DTOs (package main) for tools/go-fixtures")
	flag.Parse()

	if *goTypes != "" && *src != "" {
		if err := writeGoTypes(*src, *goTypes); err != nil {
			fmt.Fprintln(os.Stderr, "kotlin-modelgen:", err)
			os.Exit(1)
		}
		if *out == "" {
			return
		}
	}

	if *src == "" || *out == "" || *pin == "" {
		flag.Usage()
		os.Exit(2)
	}

	if err := run(*src, *out, *pin); err != nil {
		fmt.Fprintln(os.Stderr, "kotlin-modelgen:", err)
		os.Exit(1)
	}
}

func run(src, out, pin string) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
	if err != nil {
		return err
	}

	g := &generator{
		enums:   map[string]*enumDef{},
		structs: map[string]*structDef{},
	}
	if err := g.collect(file); err != nil {
		return err
	}

	header := fmt.Sprintf("// Code generated by tools/kotlin-modelgen from wavelength %s\n"+
		"// sdk/wavewalletdk/types.go. DO NOT EDIT.\n", pin)

	model, err := g.render(header, modelPkg, false)
	if err != nil {
		return err
	}
	wire, err := g.render(header, wirePkg, true)
	if err != nil {
		return err
	}

	base := filepath.Join(out, "engineering", "lightning", "wavelength")
	if err := write(filepath.Join(base, "model", "Models.kt"), model); err != nil {
		return err
	}

	return write(filepath.Join(base, "wire", "Requests.kt"), wire)
}

// writeGoTypes copies the DTO file as package main without the Go-only types
// (and their gRPC/HTTP imports), so tools/go-fixtures can marshal real values
// with encoding/json and no wavelength dependencies.
func writeGoTypes(src, dst string) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	file.Name.Name = "main"
	file.Comments = nil

	var decls []ast.Decl
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			decls = append(decls, decl)
			continue
		}
		if gd.Tok == token.IMPORT {
			gd.Specs = []ast.Spec{&ast.ImportSpec{
				Path: &ast.BasicLit{Kind: token.STRING, Value: `"time"`},
			}}
			decls = append(decls, gd)
			continue
		}
		var specs []ast.Spec
		for _, spec := range gd.Specs {
			switch s := spec.(type) {
			case *ast.TypeSpec:
				if skipTypes[s.Name.Name] {
					continue
				}
			case *ast.ValueSpec:
				if id, ok := s.Type.(*ast.Ident); ok && skipTypes[id.Name] {
					continue
				}
			}
			specs = append(specs, spec)
		}
		if len(specs) > 0 {
			gd.Specs = specs
			decls = append(decls, gd)
		}
	}
	file.Decls = decls

	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, file); err != nil {
		return err
	}

	return write(dst, buf.Bytes())
}

func write(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}

	return os.WriteFile(path, content, 0o644)
}

func (g *generator) collect(file *ast.File) error {
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		switch gd.Tok {
		case token.TYPE:
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				if err := g.addType(ts, doc.Text()); err != nil {
					return err
				}
			}

		case token.CONST:
			if err := g.addConsts(gd); err != nil {
				return err
			}
		}
	}

	for _, e := range g.enums {
		if len(e.values) == 0 {
			return fmt.Errorf("enum %s has no constants", e.name)
		}
	}

	return nil
}

func (g *generator) addType(ts *ast.TypeSpec, doc string) error {
	name := ts.Name.Name
	if !ts.Name.IsExported() || skipTypes[name] {
		return nil
	}

	switch t := ts.Type.(type) {
	case *ast.StructType:
		s := &structDef{name: name, doc: doc}
		for _, f := range t.Fields.List {
			if len(f.Names) == 0 {
				return fmt.Errorf("%s: embedded fields are not supported", name)
			}
			fdoc := f.Doc.Text()
			if fdoc == "" {
				fdoc = f.Comment.Text()
			}
			for _, n := range f.Names {
				if !n.IsExported() {
					continue
				}
				wireName := n.Name
				if f.Tag != nil {
					tag, _ := strconv.Unquote(f.Tag.Value)
					if j := reflect.StructTag(tag).Get("json"); j != "" {
						j = strings.Split(j, ",")[0]
						if j == "-" {
							continue
						}
						if j != "" {
							wireName = j
						}
					}
				}
				s.fields = append(s.fields, fieldDef{
					goName:   n.Name,
					wireName: wireName,
					typ:      f.Type,
					doc:      fdoc,
				})
			}
		}
		g.structs[name] = s
		g.order = append(g.order, name)

	case *ast.Ident:
		switch t.Name {
		case "string":
			g.enums[name] = &enumDef{name: name, kind: stringEnum, doc: doc}
		case "int32", "int", "int64":
			g.enums[name] = &enumDef{name: name, kind: intEnum, doc: doc}
		default:
			return fmt.Errorf("%s: unsupported named type over %s", name, t.Name)
		}
		g.order = append(g.order, name)

	default:
		return fmt.Errorf("%s: unsupported type %T", name, ts.Type)
	}

	return nil
}

func (g *generator) addConsts(gd *ast.GenDecl) error {
	for _, spec := range gd.Specs {
		vs := spec.(*ast.ValueSpec)
		typ, ok := vs.Type.(*ast.Ident)
		if !ok {
			continue
		}
		e, ok := g.enums[typ.Name]
		if !ok {
			continue
		}
		doc := vs.Doc.Text()
		if doc == "" {
			doc = vs.Comment.Text()
		}
		for i, n := range vs.Names {
			if i >= len(vs.Values) {
				return fmt.Errorf("%s: implicit (iota) constants are not supported", n.Name)
			}
			lit, ok := vs.Values[i].(*ast.BasicLit)
			if !ok {
				return fmt.Errorf("%s: constant value must be a literal", n.Name)
			}
			value := lit.Value
			if lit.Kind == token.STRING {
				value, _ = strconv.Unquote(lit.Value)
			}
			e.values = append(e.values, enumValue{
				goName: n.Name, value: value, doc: doc,
			})
		}
	}

	return nil
}

// isRequest reports whether a struct is a top-level verb request DTO (sent to
// the facade) rather than part of a response. EntryRequest, for example, ends
// in "Request" but is nested in Entry, so it is a model type.
func (g *generator) isRequest(name string) bool {
	if !strings.HasSuffix(name, "Request") {
		return false
	}
	for _, s := range g.structs {
		if strings.HasSuffix(s.name, "Request") && s.name != name {
			continue
		}
		for _, f := range s.fields {
			if refersTo(f.typ, name) {
				return false
			}
		}
	}

	return true
}

func refersTo(expr ast.Expr, name string) bool {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name == name
	case *ast.StarExpr:
		return refersTo(t.X, name)
	case *ast.ArrayType:
		return refersTo(t.Elt, name)
	}

	return false
}

// render emits either the public model file or the internal wire file.
func (g *generator) render(header, pkg string, requests bool) ([]byte, error) {
	var body bytes.Buffer

	for _, name := range g.order {
		if s, ok := g.structs[name]; ok {
			if g.isRequest(name) != requests {
				continue
			}
			if err := g.renderStruct(&body, s, requests); err != nil {
				return nil, err
			}
			continue
		}
		if requests {
			continue
		}
		g.renderEnum(&body, g.enums[name])
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	fmt.Fprintf(&buf, "@file:Suppress(\"RedundantVisibilityModifier\", \"MaxLineLength\")\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg)

	imports := []string{
		"kotlinx.serialization.SerialName",
		"kotlinx.serialization.Serializable",
	}
	text := body.String()
	if strings.Contains(text, "Instant") {
		imports = append(imports, "kotlin.time.Instant")
	}
	if strings.Contains(text, "ByteString") {
		imports = append(imports, "engineering.lightning.wavelength.ByteString")
	}
	if strings.Contains(text, "GoTimeSerializer") {
		imports = append(imports, "engineering.lightning.wavelength.internal.GoTimeSerializer")
	}
	if strings.Contains(text, "StringEnumSerializer") {
		imports = append(imports,
			"engineering.lightning.wavelength.internal.StringEnumSerializer",
			"engineering.lightning.wavelength.internal.OptionalStringEnumSerializer",
		)
	}
	if strings.Contains(text, "IntEnumSerializer") {
		imports = append(imports, "engineering.lightning.wavelength.internal.IntEnumSerializer")
	}
	if requests {
		for _, e := range g.sortedEnums() {
			if regexp.MustCompile(`\b` + e + `\b`).MatchString(text) {
				imports = append(imports, modelPkg+"."+e)
				if strings.Contains(text, e+"FieldSerializer") {
					imports = append(imports, modelPkg+"."+e+"FieldSerializer")
				}
			}
		}
	}
	sort.Strings(imports)
	for _, imp := range imports {
		fmt.Fprintf(&buf, "import %s\n", imp)
	}
	buf.WriteString("\n")
	buf.Write(bytes.TrimRight(body.Bytes(), "\n"))
	buf.WriteString("\n")

	return buf.Bytes(), nil
}

func (g *generator) sortedEnums() []string {
	var names []string
	for n := range g.enums {
		names = append(names, n)
	}
	sort.Strings(names)

	return names
}

func (g *generator) renderStruct(w *bytes.Buffer, s *structDef, internal bool) error {
	vis := "public"
	if internal {
		vis = "internal"
	}
	writeDoc(w, "", s.doc)
	w.WriteString("@Serializable\n")
	if len(s.fields) == 0 {
		fmt.Fprintf(w, "%s class %s\n\n", vis, s.name)
		return nil
	}

	fmt.Fprintf(w, "%s data class %s(\n", vis, s.name)
	for _, f := range s.fields {
		kt, err := g.kotlinType(f.typ)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", s.name, f.goName, err)
		}
		writeDoc(w, "    ", f.doc)
		w.WriteString("    ")
		if kt.serializer != "" {
			fmt.Fprintf(w, "@Serializable(with = %s::class) ", kt.serializer)
		}
		fmt.Fprintf(w, "@SerialName(%q) %s val %s: %s = %s,\n",
			f.wireName, vis, propertyName(f.goName), kt.name, kt.zero)
	}
	w.WriteString(")\n\n")

	return nil
}

func (g *generator) renderEnum(w *bytes.Buffer, e *enumDef) {
	writeDoc(w, "", e.doc)
	fmt.Fprintf(w, "@Serializable(with = %sSerializer::class)\n", e.name)
	wireType := "String"
	if e.kind == intEnum {
		wireType = "Int"
	}
	fmt.Fprintf(w, "public enum class %s(public val wire: %s) {\n", e.name, wireType)
	for _, v := range e.values {
		writeDoc(w, "    ", v.doc)
		entry := enumEntryName(e.name, v.goName)
		if e.kind == stringEnum {
			fmt.Fprintf(w, "    %s(%q),\n", entry, v.value)
		} else {
			fmt.Fprintf(w, "    %s(%s),\n", entry, v.value)
		}
	}
	w.WriteString("\n    /** A value this SDK version does not recognise (sent by a newer daemon). */\n")
	if e.kind == stringEnum {
		w.WriteString("    UNKNOWN(\"\\u0000unknown\"),\n    ;\n")
	} else {
		w.WriteString("    UNKNOWN(Int.MIN_VALUE),\n    ;\n")
	}
	fmt.Fprintf(w, "\n    public companion object {\n")
	fmt.Fprintf(w, "        /** Maps a wire value to its entry, or [UNKNOWN]. */\n")
	fmt.Fprintf(w, "        public fun fromWire(wire: %s): %s = entries.firstOrNull { it.wire == wire } ?: UNKNOWN\n", wireType, e.name)
	w.WriteString("    }\n}\n\n")

	if e.kind == stringEnum {
		fmt.Fprintf(w, "internal object %sSerializer : StringEnumSerializer<%s>(%q, %s::fromWire, { it.wire })\n\n",
			e.name, e.name, modelPkg+"."+e.name, e.name)
		fmt.Fprintf(w, "/** Maps an absent or empty wire value to null. */\n")
		fmt.Fprintf(w, "internal object %sFieldSerializer : OptionalStringEnumSerializer<%s>(%sSerializer)\n\n",
			e.name, e.name, e.name)
	} else {
		fmt.Fprintf(w, "internal object %sSerializer : IntEnumSerializer<%s>(%q, %s::fromWire, { it.wire })\n\n",
			e.name, e.name, modelPkg+"."+e.name, e.name)
	}
}

type ktType struct {
	name       string
	zero       string
	serializer string
}

func (g *generator) kotlinType(expr ast.Expr) (ktType, error) {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return ktType{name: "String", zero: `""`}, nil
		case "bool":
			return ktType{name: "Boolean", zero: "false"}, nil
		case "int32", "int16", "int8", "uint16", "uint8":
			return ktType{name: "Int", zero: "0"}, nil
		case "int", "int64", "uint", "uint32", "uint64":
			// uint32 widens losslessly; uint64 values above Long.MAX_VALUE
			// fail to decode rather than wrapping silently.
			return ktType{name: "Long", zero: "0L"}, nil
		case "float64", "float32":
			return ktType{name: "Double", zero: "0.0"}, nil
		}
		if e, ok := g.enums[t.Name]; ok {
			if e.kind == intEnum {
				zero := "UNKNOWN"
				for _, v := range e.values {
					if v.value == "0" {
						zero = enumEntryName(e.name, v.goName)
					}
				}
				return ktType{name: e.name, zero: e.name + "." + zero}, nil
			}
			// A Go string enum's zero value is "", meaning "unset".
			return ktType{
				name:       e.name + "?",
				zero:       "null",
				serializer: e.name + "FieldSerializer",
			}, nil
		}
		if _, ok := g.structs[t.Name]; ok {
			return ktType{name: t.Name, zero: t.Name + "()"}, nil
		}
		return ktType{}, fmt.Errorf("unknown type %s", t.Name)

	case *ast.SelectorExpr:
		if pkg, ok := t.X.(*ast.Ident); ok && pkg.Name == "time" && t.Sel.Name == "Time" {
			return ktType{name: "Instant?", zero: "null", serializer: "GoTimeSerializer"}, nil
		}
		return ktType{}, fmt.Errorf("unsupported selector type")

	case *ast.StarExpr:
		inner, err := g.kotlinType(t.X)
		if err != nil {
			return ktType{}, err
		}
		if strings.HasSuffix(inner.name, "?") {
			return inner, nil
		}
		return ktType{name: inner.name + "?", zero: "null", serializer: inner.serializer}, nil

	case *ast.ArrayType:
		if t.Len != nil {
			return ktType{}, fmt.Errorf("fixed-size arrays are not supported")
		}
		if id, ok := t.Elt.(*ast.Ident); ok && id.Name == "byte" {
			return ktType{name: "ByteString", zero: "ByteString.EMPTY"}, nil
		}
		inner, err := g.kotlinType(t.Elt)
		if err != nil {
			return ktType{}, err
		}
		// List elements use the type's own serializer; a nullable enum
		// element would mean "" entries, which the daemon never sends.
		name := strings.TrimSuffix(inner.name, "?")
		return ktType{name: "List<" + name + ">", zero: "emptyList()"}, nil
	}

	return ktType{}, fmt.Errorf("unsupported type %T", expr)
}

// acronyms are the upper-case runs the Go source uses as single words.
var acronyms = []string{
	"CPFP", "CLTV", "VTXO", "UTXO", "HTLC", "TLS", "URL", "PRF", "CSV",
	"OOR", "PPM", "RPC", "ID", "DB",
}

// words splits a Go identifier into words, keeping known acronyms (and their
// plural "s") together: RecoveredVTXOs -> Recovered VTXOs.
func words(ident string) []string {
	var out []string
	for i := 0; i < len(ident); {
		matched := false
		for _, a := range acronyms {
			if !strings.HasPrefix(ident[i:], a) {
				continue
			}
			end := i + len(a)
			if end < len(ident) && ident[end] == 's' &&
				(end+1 == len(ident) || isUpper(ident[end+1])) {
				end++
			}
			// Only take the acronym if it ends a word.
			if end == len(ident) || isUpper(ident[end]) || isDigit(ident[end]) {
				out = append(out, ident[i:end])
				i = end
				matched = true
				break
			}
		}
		if matched {
			continue
		}
		j := i + 1
		if isUpper(ident[i]) {
			// A run of capitals not in the acronym list: treat all but
			// the last (which starts the next word) as one word.
			k := j
			for k < len(ident) && isUpper(ident[k]) {
				k++
			}
			if k-i > 1 {
				if k < len(ident) && !isDigit(ident[k]) {
					k--
				}
				out = append(out, ident[i:k])
				i = k
				continue
			}
		}
		for j < len(ident) && !isUpper(ident[j]) {
			j++
		}
		out = append(out, ident[i:j])
		i = j
	}

	return out
}

func isUpper(b byte) bool { return b >= 'A' && b <= 'Z' }
func isDigit(b byte) bool { return b >= '0' && b <= '9' }

var kotlinKeywords = map[string]bool{
	"as": true, "break": true, "class": true, "continue": true, "do": true,
	"else": true, "false": true, "for": true, "fun": true, "if": true,
	"in": true, "interface": true, "is": true, "null": true, "object": true,
	"package": true, "return": true, "super": true, "this": true,
	"throw": true, "true": true, "try": true, "typealias": true,
	"typeof": true, "val": true, "var": true, "when": true, "while": true,
}

func propertyName(goName string) string {
	ws := words(goName)
	var b strings.Builder
	for i, w := range ws {
		lw := strings.ToLower(w)
		if i == 0 {
			b.WriteString(lw)
			continue
		}
		b.WriteString(strings.ToUpper(lw[:1]) + lw[1:])
	}
	name := b.String()
	if kotlinKeywords[name] {
		return "`" + name + "`"
	}

	return name
}

func enumEntryName(typeName, constName string) string {
	rest := strings.TrimPrefix(constName, typeName)
	if rest == "" {
		rest = constName
	}
	ws := words(rest)
	for i := range ws {
		ws[i] = strings.ToUpper(ws[i])
	}

	return strings.Join(ws, "_")
}

func writeDoc(w *bytes.Buffer, indent, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	doc = strings.ReplaceAll(doc, "*/", "*&#47;")
	doc = strings.ReplaceAll(doc, "/*", "&#47;*")
	lines := strings.Split(doc, "\n")
	fmt.Fprintf(w, "%s/**\n", indent)
	for _, l := range lines {
		l = strings.TrimRight(l, " \t")
		if l == "" {
			fmt.Fprintf(w, "%s *\n", indent)
			continue
		}
		fmt.Fprintf(w, "%s * %s\n", indent, l)
	}
	fmt.Fprintf(w, "%s */\n", indent)
}
