#!/usr/bin/env bash
#
# package-swift.sh writes Package.swift for a release: a Swift package with
# two binary targets, the WavelengthKit XCFramework built here and the pinned
# gomobile Wavewalletdk.xcframework that it links against (ADR 0004).
#
# Usage: scripts/package-swift.sh <release-tag> <dist-dir>
#   <dist-dir> must contain WavelengthKit.xcframework.zip and
#   Wavewalletdk.xcframework.zip; both are uploaded to the GitHub release.

set -euo pipefail

TAG="$1"
DIST="$2"
REPO="${GITHUB_REPOSITORY:-lightninglabs/wavelength-kmp}"
BASE="https://github.com/${REPO}/releases/download/${TAG}"

checksum() { swift package compute-checksum "$1"; }

kit_sum="$(checksum "${DIST}/WavelengthKit.xcframework.zip")"
go_sum="$(checksum "${DIST}/Wavewalletdk.xcframework.zip")"

cat > Package.swift <<SWIFT
// swift-tools-version: 5.9
// Generated by scripts/package-swift.sh for ${TAG}. Do not edit.
import PackageDescription

let package = Package(
    name: "WavelengthKit",
    platforms: [.iOS(.v15)],
    products: [
        .library(name: "WavelengthKit", targets: ["WavelengthKit", "Wavewalletdk", "WavelengthKitLinks"]),
    ],
    targets: [
        .binaryTarget(
            name: "WavelengthKit",
            url: "${BASE}/WavelengthKit.xcframework.zip",
            checksum: "${kit_sum}"
        ),
        .binaryTarget(
            name: "Wavewalletdk",
            url: "${BASE}/Wavewalletdk.xcframework.zip",
            checksum: "${go_sum}"
        ),
        // The Go runtime's resolver needs libresolv.
        .target(
            name: "WavelengthKitLinks",
            path: "swift/WavelengthKitLinks",
            linkerSettings: [.linkedLibrary("resolv")]
        ),
    ]
)
SWIFT
echo "==> wrote Package.swift for ${TAG}"
