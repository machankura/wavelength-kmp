#!/usr/bin/env bash
#
# generate-models.sh regenerates the Kotlin wire models in wavelength-core
# from the pinned wavelength release's sdk/wavewalletdk/types.go, and the golden
# JSON fixtures (tools/go-fixtures) that the codec tests decode.
#
# The source is the daemon nested at experimental/wavelength, whose gitlink is the
# pin (docs/adr/0006-daemon-source.md). Set WAVELENGTH_DIR to read types.go from
# another checkout. With neither, it comes from the release's
# wavelength-source-<tag>.tar.gz, checked against the SHA-256 listed in that
# release's manifest-<tag>.txt.
#
# Usage:
#   scripts/generate-models.sh           # rewrite the generated sources
#   scripts/generate-models.sh --check   # fail if they differ from the pin

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TAG="${WAVELENGTH_VERSION:-$(tr -d '[:space:]' < "${ROOT}/wavelength.version")}"
REPO="${WAVELENGTH_REPO:-machankura/wavelength}"
if [[ -z "${WAVELENGTH_DIR:-}" && -f "${ROOT}/experimental/wavelength/sdk/wavewalletdk/types.go" ]]; then
	WAVELENGTH_DIR="${ROOT}/experimental/wavelength"
fi
KOTLIN_ROOT="${ROOT}/wavelength-core/src/commonMain/kotlin"
FIXTURES="engineering/lightning/wavelength/GoFixtures.kt"
TEST_ROOT="${ROOT}/wavelength-core/src/commonTest/kotlin"
GENERATED=(
	"engineering/lightning/wavelength/model/Models.kt"
	"engineering/lightning/wavelength/wire/Requests.kt"
)

check=0
[[ "${1:-}" == "--check" ]] && check=1

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

if [[ -n "${WAVELENGTH_DIR:-}" ]]; then
	types="${WAVELENGTH_DIR}/sdk/wavewalletdk/types.go"
else
	base="https://github.com/${REPO}/releases/download/${TAG}"
	tarball="wavelength-source-${TAG}.tar.gz"
	curl -fsSL --retry 3 -o "${work}/${tarball}" "${base}/${tarball}"
	curl -fsSL --retry 3 -o "${work}/manifest.txt" "${base}/manifest-${TAG}.txt"
	want="$(awk -v f="${tarball}" '$2 == f {print $1}' "${work}/manifest.txt")"
	if command -v sha256sum >/dev/null 2>&1; then
		got="$(sha256sum "${work}/${tarball}" | cut -d' ' -f1)"
	else
		got="$(shasum -a 256 "${work}/${tarball}" | cut -d' ' -f1)"
	fi
	if [[ -z "${want}" || "${got}" != "${want}" ]]; then
		echo "error: ${tarball} digest ${got} does not match manifest (${want:-missing})" >&2
		exit 1
	fi
	tar -xzf "${work}/${tarball}" -C "${work}" \
		wavelength-source/sdk/wavewalletdk/types.go \
		wavelength-source/sdk/wavewalletdk/mobile/config.go
	types="${work}/wavelength-source/sdk/wavewalletdk/types.go"
fi

out="${KOTLIN_ROOT}"
[[ "${check}" == 1 ]] && out="${work}/out"

(cd "${ROOT}/tools/kotlin-modelgen" && go run . -src "${types}" -out "${out}" -pin "${TAG}" \
	-go-types "${ROOT}/tools/go-fixtures/types.go")

# Golden fixtures: real encoding/json output, as Kotlin string constants.
fixtures_out="${TEST_ROOT}/${FIXTURES}"
[[ "${check}" == 1 ]] && fixtures_out="${work}/test/${FIXTURES}"
mkdir -p "$(dirname "${fixtures_out}")"
{
	echo "// Code generated by scripts/generate-models.sh from tools/go-fixtures"
	echo "// (wavelength ${TAG} types.go). DO NOT EDIT."
	echo "package engineering.lightning.wavelength"
	echo
	echo "/** Golden encoding/json output for the wavelength SDK DTOs. */"
	echo "internal object GoFixtures {"
	(cd "${ROOT}/tools/go-fixtures" && go run .) | while IFS=$'\t' read -r name json; do
		const="$(echo "${name}" | tr '[:lower:]' '[:upper:]')"
		json="${json//\$/\$\{\'\$\'\}}"
		printf '    const val %s: String = """%s"""\n' "${const}" "${json}"
	done
	# The json tags of the facade's Start config (sdk/wavewalletdk/mobile/config.go).
	keys="$(sed -n '/^type mobileConfig struct/,/^}/p' "$(dirname "${types}")/mobile/config.go" \
		| grep -o 'json:"[a-z_]*"' | sed 's/json:"\(.*\)"/\1/' | sort | paste -sd, -)"
	printf '    const val MOBILE_CONFIG_KEYS: String = "%s"\n' "${keys}"
	echo "}"
} > "${fixtures_out}"

if [[ "${check}" == 1 ]]; then
	status=0
	for f in "${GENERATED[@]}"; do
		if ! diff -u "${KOTLIN_ROOT}/${f}" "${out}/${f}"; then
			status=1
		fi
	done
	if ! diff -u "${TEST_ROOT}/${FIXTURES}" "${fixtures_out}"; then
		status=1
	fi
	if [[ "${status}" != 0 ]]; then
		echo "error: generated models are stale; run scripts/generate-models.sh" >&2
		exit 1
	fi
	echo "==> generated models match ${TAG}"
else
	echo "==> generated models from ${TAG}"
fi
